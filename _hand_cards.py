w("Буква | № i | n−i+1 | замена")
for ch in "БАЛ":
    i = numUP(ch); j = 32-i+1
    w(f"  {ch}   |  {i:>2} |  {j:>2}   |   {UP[j-1]}")
w(f"Открытый текст:  БАЛ")
w(f"Шифртекст:       {atb.atbash('БАЛ')}")

