import sys, io, importlib.util, contextlib
sys.stdout.reconfigure(encoding='utf-8', errors='replace')

def load(n, f):
    s = importlib.util.spec_from_file_location(n, f); m = importlib.util.module_from_spec(s)
    with contextlib.redirect_stdout(io.StringIO()): s.loader.exec_module(m)
    return m

OUT = []
def w(s=""): OUT.append(s)
def card(t): w("\n" + "═"*64); w("  " + t); w("═"*64)

UP = "АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"   # А=1..Я=32 (индекс+1)
def numUP(ch): return UP.index(ch)+1

