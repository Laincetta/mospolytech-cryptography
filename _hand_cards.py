# ── 5. ШЕННОН (ЛКГ) ──────────────────────────────────────────────────────────
card("№13. ШЕННОН (ЛКГ) — слово «баба»,  a=5, c=3, T0=1  (mod 32)")
low = "абвгдежзийклмнопрстуфхцчшщъыьэюя"
msg = "баба"; m = [low.index(c)+1 for c in msg]
g = []; T = 1
for _ in msg: T = (5*T+3) % 32; g.append(T)
w("Гамма γ_i = (5·T + 3) mod 32:")
prev = 1
for i in range(len(msg)):
    w(f"  γ{i} = (5·{prev} + 3) mod 32 = {g[i]}"); prev = g[i]
w(f"Буквы → числа:  б=2, а=1, б=2, а=1")
res = []
for i in range(len(msg)):
    s = (m[i]+g[i]) % 32; s = s if s else 32; res.append(s)
    w(f"  c{i} = ({m[i]} + {g[i]}) mod 32 = {res[i]}")
w(f"Шифртекст (числа):  " + " ".join(f"{x:02d}" for x in res))

# ── 6. RSA ───────────────────────────────────────────────────────────────────
card("№21. RSA — буквы «БВ»,  P=37, Q=41, E=7")
P,Q,E = 37,41,7; N=P*Q; phi=(P-1)*(Q-1); D=pow(E,-1,phi)
w(f"N = P·Q = 37·41 = {N};   φ(N) = 36·40 = {phi};   D = E⁻¹ mod φ(N) = {D}")
